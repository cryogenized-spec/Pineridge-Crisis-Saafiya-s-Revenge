"""Bake cosmetic vehicle damage artwork in the existing vehicle projection."""
from math import cos, sin, pi
from pathlib import Path
import random

from PIL import Image, ImageDraw

from render_environment import ELEVATION, ROOT, car

SIZE = 288, 136
ART = ROOT / "environment/vehicle_damage"
CAR_MODELS = {
    "sedan_silver": "sedan", "sedan_ochre": "sedan",
    "hatchback_russet": "hatchback", "hatchback_sage": "hatchback",
    "utility_ivory": "utility", "security": "security", "saafiya_car": "mustang"
}


def project(point, heading):
    x,y,z = point
    horizontal = x*cos(heading)-y*sin(heading)
    depth = x*sin(heading)+y*cos(heading)
    return (.5+horizontal/5.74, .5-(depth*sin(ELEVATION)+(z-.48)*cos(ELEVATION))/(5.74*SIZE[1]/SIZE[0]))


def shattered(polygon, seed):
    width, height = (size*3 for size in SIZE)
    outline = [(u*width,v*height) for u,v in polygon]
    mask = Image.new("L", (width,height))
    ImageDraw.Draw(mask).polygon(outline,fill=255)
    art = Image.new("RGBA", mask.size)
    draw = ImageDraw.Draw(art)
    draw.polygon(outline,fill="#273241")
    randomizer = random.Random(seed)
    # Scattered glass around the pane's edge leaves the middle visibly open.
    for i in range(4):
        a,b = outline[i],outline[(i+1)%4]
        center = (sum(x for x,y in outline)/4,sum(y for x,y in outline)/4)
        for p in range(11):
            t = (p + randomizer.random()*.5)/11
            pt = (a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t)
            s = min(1, t+randomizer.uniform(.045,.14))
            end = (a[0]+(b[0]-a[0])*s,a[1]+(b[1]-a[1])*s)
            depth = randomizer.uniform(.16,.77)
            tip = (pt[0]+(center[0]-pt[0])*depth,pt[1]+(center[1]-pt[1])*depth)
            draw.polygon([pt, end, tip],fill=randomizer.choice(["#546c76","#637c87","#9aaeb2","#344854","#748e95"]))
            draw.line([pt, tip, end],fill="#9fabac",width=2)
    art.putalpha(mask)
    return art.resize(SIZE, Image.Resampling.LANCZOS)


def punctures():
    sheet = Image.new("RGBA", (144,48))
    for idx in range(3):
        art = Image.new("RGBA", (144,144))
        draw = ImageDraw.Draw(art)
        randomizer = random.Random(852+idx)
        out = []
        for i in range(16):
            angle = i*pi/8
            radius = randomizer.uniform(36,59)
            out.append((72+cos(angle)*radius,72+sin(angle)*radius*.87))
        draw.polygon(out,fill="#4b4b52")
        for i in [0,1,3,5,6,8,9,12,14]:
            x,y=out[i]
            draw.line((x,y,72+(x-72)*.36,72+(y-72)*.36),fill=randomizer.choice(["#a99e91","#bfb6a8","#6d6869"]),width=5)
        draw.ellipse((47,52,97,98),fill="#1d2028")
        draw.ellipse((58,60,87,91),fill="#11141a")
        sheet.paste(art.resize((48,48),Image.Resampling.LANCZOS),(idx*48,0))
    return sheet


if __name__ == "__main__":
    ART.mkdir(parents=True,exist_ok=True)
    catalogue = ['extends RefCounted', '# Generated by tools/render_vehicle_damage.py.', 'const PANELS := {']
    for key,style in CAR_MODELS.items():
        catalogue.append(f'\t"{key}": [')
        for suffix, heading in (("east",0),("west",pi)):
            geometry = car(style,"636775").windscreen
            polygon = [project(point,heading) for point in geometry]
            file = f"{key}_{suffix}.png"
            shattered(polygon,19 if heading == 0 else 39).save(ART/file,optimize=True)
            points = ", ".join(f"Vector2({x:.6f}, {y:.6f})" for x,y in polygon)
            catalogue.append(f'\t\t{{"glass":[{points}], "shattered":preload("res://assets/environment/vehicle_damage/{file}")}},')
        catalogue.append('\t],')
    catalogue += ['}', '']
    (Path(__file__).resolve().parents[1]/"scripts/vehicle_damage_art.gd").write_text("\n".join(catalogue))
    punctures().save(ART/"panel_punctures.png",optimize=True)
